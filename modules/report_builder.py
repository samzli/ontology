def _metric_rows(
    pack: Dict[str, Any], computed: Dict[str, Any]
) -> List[Dict[str, Any]]:
    vals = computed.get("metrics", {})
    out = []
    for f in pack.get("formulas", []):
        if f["key"] in vals:
            v = vals[f["key"]]
            out.append(
                {
                    "key": f["key"],
                    "label": f.get("label") or f["key"],
                    "value": v,
                    "fmt": f.get("fmt", "number"),
                    "unit": f.get("unit", ""),
                    "expression": f.get("expression", ""),
                }
            )
    return out


def _fmt_metric(v: Any, fmt: str) -> str:
    return rc.format_value(v, fmt, 2)


def _chain_from_session(
    pack: Dict[str, Any], qa_items: List[Dict[str, Any]]
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    visual = svc.visual_graph(pack)
    link_map = {lk["id"]: lk for lk in visual["links"]}
    node_meta = {n["key"]: n for n in pack.get("nodes", [])}
    node_map: Dict[str, Dict[str, Any]] = {}
    edges: Dict[str, Dict[str, Any]] = {}

    def add_node(nid: str, override: Optional[Dict[str, Any]] = None) -> None:
        if nid in node_map:
            return
        meta = node_meta.get(nid, {})
        node_map[nid] = {
            "id": nid,
            "label": (override or {}).get("label") or meta.get("label") or nid,
            "grp": (override or {}).get("grp") or meta.get("grp", ""),
            "value": (override or {}).get("value", meta.get("value", "")),
        }

    for qa in qa_items:
        g = qa.get("graph") or {}
        for n in g.get("nodes", []):
            if isinstance(n, str):
                add_node(n)
            elif isinstance(n, dict):
                nid = n.get("id") or n.get("key")
                if nid:
                    add_node(nid, n)
        for eid in g.get("edge_ids", []):
            if eid in link_map and eid not in edges:
                lk = link_map[eid]
                edges[eid] = {
                    "id": eid,
                    "source": lk["source"],
                    "target": lk["target"],
                    "label": lk.get("label", ""),
                    "edge_type": lk.get("type"),
                }
    nodes = list(node_map.values())
    if nodes and edges:
        return nodes, list(edges.values())
    # Fallback: core nodes from the pack definition + edges among them.
    core = [n for n in pack.get("nodes", []) if n.get("is_core")][:12]
    if not core:
        core = pack.get("nodes", [])[:12]
    ids = {n["key"] for n in core}
    fallback_edges = [
        {
            "id": lk["id"],
            "source": lk["source"],
            "target": lk["target"],
            "label": lk.get("label", ""),
            "edge_type": lk.get("type"),
        }
        for lk in visual["links"]
        if lk["source"] in ids and lk["target"] in ids
    ]
    n_out = [
        {
            "id": n["key"],
            "label": n.get("label") or n["key"],
            "grp": n.get("grp", ""),
            "value": n.get("value", ""),
        }
        for n in core
    ]
    return n_out, fallback_edges


def _ai_interpretation(
    pack: Dict[str, Any], qa_items: List[Dict[str, Any]]
) -> Optional[str]:
    from modules.llm_client import (
        ConfiguredLLM,
        build_system_prompt,
        get_default_client_config,
    )

    with get_conn() as conn:
        cfg = get_default_client_config(conn)
        if cfg is None:
            return None
        client = ConfiguredLLM(cfg)
        context = svc.build_llm_context(pack)
        system = build_system_prompt(context)
        qa_blob = "\n".join(
            f"Q: {q.get('question','')}\nA: {q.get('answer','')[:600]}"
            for q in qa_items[:12]
        )
        prompt = (
            "Based ONLY on the ontology knowledge base and the Q&A record below, write the "
            "'Business Interpretation & Recommendations' section of a management report.\n"
            "Requirements:\n"
            "- 4-6 bullet points, each starting with a bold one-line takeaway followed by the "
            "rationale with concrete figures.\n"
            "- Cover: what the numbers say, the main driver/risks visible in the impact chain, "
            "and 2-3 recommended next actions.\n"
            "- English, concise Markdown, no preamble, no invented facts.\n\n"
            f"Q&A record:\n{qa_blob}"
        )
        result = client.answer(system, prompt, max_tokens=900)
        if result.get("status") == "success":
            return result["response"].strip()
        return None


