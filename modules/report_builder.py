def _inline_html(text: str) -> str:
    """Escape a string and convert inline Markdown (code, bold, italic, links).

    Args:
        text (str): Inline Markdown fragment to convert.

    Returns:
        str: HTML-escaped fragment with inline Markdown tags converted.

    Example:
        >>> _inline_html("**VNB** is `growing`")
        '<strong>VNB</strong> is <code>growing</code>'
    """
    text = html.escape(text, quote=False)
    # Protect images so the link rule below cannot turn them into anchors.
    held: List[str] = []

    def _hold(m):
        """Stash an image match and return a placeholder token."""
        held.append(m.group(0))
        return f"\x00{len(held) - 1}\x00"

    text = re.sub(r"!\[[^\]]*\]\([^)]+\)", _hold, text)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<em>\1</em>", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', text)
    for i, s in enumerate(held):
        text = text.replace(f"\x00{i}\x00", s)
    return text


def md_to_html_fragment(md: str) -> str:
    """Convert the Markdown subset produced by Onti into an HTML fragment.

    Handles headings, horizontal rules, tables, bullet/numbered lists,
    standalone images (kept as raw Markdown for the embedding pass) and
    paragraphs.

    Args:
        md (str): Markdown document to convert; ``None``/empty yields ``""``.

    Returns:
        str: HTML fragment with one element per source block.

    Example:
        >>> md_to_html_fragment("# Title")
        '<h1>Title</h1>'
    """
    lines = (md or "").replace("\r\n", "\n").split("\n")
    out: List[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        if line.strip() == "---":
            out.append("<hr/>")
            i += 1
            continue
        m = re.match(r"^(#{1,6})\s+(.*)$", line)
        if m:
            lvl = len(m.group(1))
            out.append(f"<h{lvl}>{_inline_html(m.group(2))}</h{lvl}>")
            i += 1
            continue
        if line.lstrip().startswith("|"):
            tbl = []
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                tbl.append(lines[i].strip())
                i += 1
            rows = [[c.strip() for c in r.strip("|").split("|")] for r in tbl]
            rows = [
                r
                for r in rows
                if not all(re.fullmatch(r":?-{2,}:?", c or "") for c in r)
            ]
            if rows:
                thead = "".join(f"<th>{_inline_html(c)}</th>" for c in rows[0])
                body = ""
                for r in rows[1:]:
                    body += (
                        "<tr>"
                        + "".join(f"<td>{_inline_html(c)}</td>" for c in r)
                        + "</tr>"
                    )
                out.append(
                    f"<table><thead><tr>{thead}</tr></thead><tbody>{body}</tbody></table>"
                )
            continue
        if re.match(r"^\s*[-*]\s+", line):
            items = []
            while i < len(lines) and re.match(r"^\s*[-*]\s+", lines[i]):
                items.append(re.sub(r"^\s*[-*]\s+", "", lines[i]))
                i += 1
            out.append(
                "<ul>" + "".join(f"<li>{_inline_html(x)}</li>" for x in items) + "</ul>"
            )
            continue
        if re.match(r"^\s*\d+\.\s+", line):
            items = []
            while i < len(lines) and re.match(r"^\s*\d+\.\s+", lines[i]):
                items.append(re.sub(r"^\s*\d+\.\s+", "", lines[i]))
                i += 1
            out.append(
                "<ol>" + "".join(f"<li>{_inline_html(x)}</li>" for x in items) + "</ol>"
            )
            continue
        # standalone image line: keep raw markdown for the embedding pass
        imgm = re.match(r"^!\[[^\]]*\]\([^)]+\)\s*$", line.strip())
        if imgm:
            out.append(line.strip())
            i += 1
            continue
        # paragraph (gather consecutive plain lines)
        para = [line]
        i += 1
        while (
            i < len(lines)
            and lines[i].strip()
            and not re.match(r"^(#{1,6}\s|\s*[-*]\s|\s*\d+\.\s|\||---|!\[)", lines[i])
        ):
            para.append(lines[i])
            i += 1
        out.append("<p>" + _inline_html(" ".join(p.strip() for p in para)) + "</p>")
    return "\n".join(out)


