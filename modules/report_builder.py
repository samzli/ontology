def build_report(
    conn,
    *,
    owner_id: Optional[int],
    title: str,
    scope: str = "session",
    sections: Optional[List[str]] = None,
    include_ai: bool = False,
    qa_items: Optional[List[Dict[str, Any]]] = None,
    pack_id: Optional[int] = None,
    actor: str = "system",
    text_only: bool = False,
) -> Dict[str, Any]:
    """Generate a report (Markdown, HTML and PDF) and register it in the database.

    Sections are assembled dynamically from the data that exists, numbered in
    render order: summary, Q&A, ontology evidence, KPI, charts, ontology graph,
    analytics, AI interpretation and appendix.

    Args:
        conn: Open database connection used for loading the pack and auditing.
        owner_id (int | None): User id owning the report; ``None`` for system.
        title (str): Report title shown on the cover.
        scope (str): Report scope label, e.g. ``"session"`` or ``"pack"``.
        sections (list[str] | None): Sections to include; defaults to
            summary, qa, evidence, kpi and charts.
        include_ai (bool): Whether to request the LLM interpretation section.
        qa_items (list[dict] | None): Q&A records to embed in the report.
        pack_id (int | None): Ontology pack to use; defaults to the active pack.
        actor (str): Actor name recorded in the audit log.
        text_only (bool): Skip all ontology-derived content (no pack data).

    Returns:
        dict: Report metadata with ``id``, ``uid``, output ``dir`` and the
        ``md_path``/``html_path``/``pdf_path`` file locations, the included
        section names and the ``ai_included`` flag.

    Raises:
        OSError: If the report directory or output files cannot be written.

    Example:
        >>> info = build_report(conn, owner_id=1, title="Q3 VNB review")
        >>> info["sections"]
        ['summary', 'kpi', 'charts', 'appendix']
    """
    qa_items = qa_items or []
    sections = sections or ["summary", "qa", "evidence", "kpi", "charts"]
    pid = pack_id
    if pid is None:
        row = conn.execute("SELECT id FROM ontology_packs WHERE is_active=1").fetchone()
        pid = row["id"] if row else None
    pack_name = "(empty)"
    pack = {"formulas": [], "nodes": [], "links": [], "tables": []}
    computed = {"metrics": {}}
    tables_rows: List[Dict[str, Any]] = []
    if pid is not None:
        loaded = svc.load_pack(conn, pid)
        if loaded is not None:
            pack = loaded
            computed = svc.compute_pack(pack, strict=False)
            pack_name = pack.get("name", "Pack")
    # Instance rows are already embedded on the loaded pack tables.
    tables_rows = pack.get("tables", [])
    ds_names = (
        {
            r["id"]: r["name"]
            for r in conn.execute(
                "SELECT id,name FROM datasets WHERE pack_id=?", (pid,)
            ).fetchall()
        }
        if pid
        else {}
    )

    metric_rows = _metric_rows(pack, computed)
    # KPI cards: first six formatted metrics.
    kpi_cards = [
        {"label": m["label"], "display": _fmt_metric(m["value"], m["fmt"])}
        for m in metric_rows[:REPORT_METRIC_ROWS]
    ]

    # Charts.
    chart_specs, chart_notes = rc.auto_chart_specs(tables_rows)
    chain_nodes, chain_edges = _chain_from_session(pack, qa_items)

    uid = uuid.uuid4().hex[:REPORT_UID_CHARS]
    rdir = os.path.join(REPORTS_ROOT, uid)
    cdir = os.path.join(rdir, "charts")
    os.makedirs(cdir, exist_ok=True)

    charts_meta = []
    for idx, spec in enumerate(chart_specs, start=1):
        fname = f"chart_{idx:02d}.png"
        with open(os.path.join(cdir, fname), "wb") as f:
            f.write(rc.render_chart(spec))
        charts_meta.append(
            {"title": spec["title"], "file": fname, "note": chart_notes[idx - 1]}
        )
    section_charts = "charts" in sections and bool(charts_meta)
    chain_png = None
    section_chain = "evidence" in sections and bool(chain_nodes)
    if section_chain:
        chain_png = rc.render_chain_graph(
            chain_nodes, chain_edges, title=f"Impact chain — {pack_name}"
        )
        with open(os.path.join(cdir, "impact_chain.png"), "wb") as f:
            f.write(chain_png)

    # Full ontology knowledge graph (section "ontology").
    section_ontology = "ontology" in sections and bool(pack.get("nodes"))
    if section_ontology:
        onto_nodes = [
            {
                "id": n["id"],
                "label": n.get("label") or n["id"],
                "grp": n.get("group", ""),
            }
            for n in pack.get("nodes", [])[:REPORT_GRAPH_NODES]
        ]
        onto_edges = [
            {
                "source": l.get("source"),
                "target": l.get("target"),
                "label": l.get("label") or l.get("edge_type") or "",
            }
            for l in pack.get("links", [])
            if l.get("source") and l.get("target")
        ]
        try:
            with open(os.path.join(cdir, "ontology_graph.png"), "wb") as f:
                f.write(
                    rc.render_chain_graph(
                        onto_nodes, onto_edges, title=f"Ontology graph — {pack_name}"
                    )
                )
        except Exception:
            section_ontology = False

    # Performance analytics tables (section "analytics").
    att_data = None
    ag_data = None
    section_analytics = "analytics" in sections and bool(tables_rows)
    if section_analytics:
        try:
            att_data = an.mom_attribution(tables_rows, None)
        except Exception:
            att_data = None
        try:
            ag_data = an.agent_stats(tables_rows)
        except Exception:
            ag_data = None
        if not att_data and not ag_data:
            section_analytics = False
    att_rows: List[Dict[str, Any]] = []
    if att_data:
        fac = att_data.get("factors") or {}
        for key, lab in (
            ("agent_effect", "Headcount effect"),
            ("productivity_effect", "Productivity effect"),
            ("mix_effect", "Product mix effect"),
        ):
            att_rows.append({"factor": lab, "delta": fac.get(key, 0.0)})
        att_rows.append(
            {
                "factor": "Total VNB movement",
                "delta": att_data.get("delta_total_vnb", 0.0),
            }
        )
    ag_rows: List[Dict[str, Any]] = []
    if ag_data:
        for c in ag_data.get("by_channel", []):
            ag_rows.append(
                {
                    "channel": c.get("channel_id") or "–",
                    "registered": c.get("registered", 0),
                    "active": c.get("active", 0),
                    "ratio": f"{(c.get('active_ratio') or 0) * 100:.0f}%",
                    "avg_prod": f"{c.get('avg_prod') or 0:.2f}",
                }
            )

    # AI section.
    ai_text = None
    ai_status = "off"
    if include_ai and "ai" in sections + ["ai"]:
        ai_text = _ai_interpretation(pack, qa_items)
        ai_status = "included" if ai_text else "requested but no enabled model"

    # Dynamic section numbering.
    sec_no = 1
    n_qa = sec_no + 1 if "qa" in sections and qa_items else None
    if n_qa:
        sec_no += 1
    n_chain = sec_no + 1 if section_chain else None
    if section_chain:
        sec_no += 1
    n_kpi = sec_no + 1 if "kpi" in sections and metric_rows else None
    if n_kpi:
        sec_no += 1
    n_charts = sec_no + 1 if section_charts else None
    if section_charts:
        sec_no += 1
    n_ontology = sec_no + 1 if section_ontology else None
    if section_ontology:
        sec_no += 1
    n_analytics = sec_no + 1 if section_analytics else None
    if section_analytics:
        sec_no += 1
    n_ai = sec_no + 1 if ai_text else None
    if ai_text:
        sec_no += 1
    n_appendix = sec_no + 1

    takeaways: List[str] = []
    narrative = ""
    if text_only:
        # No-ontology report: say so plainly instead of quoting the pack
        # narrative and metric figures that were deliberately excluded.
        takeaways.append(
            "This report was generated with the ontology switched **off** — "
            "text-only mode. No data tables, metric formulas, knowledge graph, "
            "charts or impact chains were used, so the figures in a normal "
            "report are intentionally absent here."
        )
    else:
        try:
            narrative = svc.render_narrative(pack, computed).strip()
        except Exception:
            narrative = (pack.get("narrative") or "").strip()
    if narrative:
        # Strip leading markdown heading for the one-line exec-summary takeaway.
        plain = re.sub(r"^#+\s*", "", narrative.replace("\n", " "))
        first = re.split(r"(?<=[.!?])\s", plain, 1)[0]
        takeaways.append(f"Ontology context — {first}")
    if qa_items:
        modes = {
            "rules": sum(1 for q in qa_items if q.get("mode") != "ai"),
            "ai": sum(1 for q in qa_items if q.get("mode") == "ai"),
        }
        takeaways.append(
            f"Analysed **{len(qa_items)} question(s)** "
            f"({modes['rules']} rule-engine, {modes['ai']} AI-assisted)."
        )
    if metric_rows and not text_only:
        takeaways.append(
            "Key figures: "
            + ", ".join(
                f"**{m['label']} {_fmt_metric(m['value'], m['fmt'])}**"
                for m in metric_rows[:REPORT_SUMMARY_METRICS]
            )
            + "."
        )
    for note in chart_notes[:REPORT_CHART_NOTES] if not text_only else []:
        clean = re.sub(r"\*\*", "", note)
        takeaways.append(clean)
    if not takeaways:
        takeaways.append(
            "No structured data exists for this scope yet; "
            "import data or ask questions to populate the next report."
        )

    # Per-QA evidence labels.
    qa_view = []
    label_lookup = {
        n["key"]: (n.get("label") or n["key"]) for n in pack.get("nodes", [])
    }
    for q in qa_items:
        g = q.get("graph") or {}
        raw_nodes = g.get("nodes", [])[:8]
        node_labels = ", ".join(
            n if isinstance(n, str) else str(n.get("label") or n.get("id"))
            for n in raw_nodes
        )
        node_labels = ", ".join(
            label_lookup.get(x.strip(), x.strip())
            for x in node_labels.split(",")
            if x.strip()
        )
        qa_view.append(
            {
                "question": q.get("question", ""),
                "answer": (q.get("answer") or "").strip(),
                "mode": "AI Assisted" if q.get("mode") == "ai" else "Rules Engine",
                "latency_ms": q.get("latency_ms"),
                "nodes": node_labels,
            }
        )

    import json as _json

    glossary = []
    for e in pack.get("entities", []):
        attrs = [
            a.get("label_en") or a["key"]
            for a in pack.get("attributes", [])
            if a.get("entity_key") == e["key"]
        ]
        glossary.append(
            {
                "label": e.get("label_en") or e["key"],
                "layer": e.get("layer", 3),
                "attrs": ", ".join(attrs[:REPORT_ATTR_LABELS])
                + (" …" if len(attrs) > REPORT_ATTR_LABELS else ""),
            }
        )
    formula_rows = [
        {"label": f.get("label") or f["key"], "expression": f.get("expression", "")}
        for f in pack.get("formulas", [])
    ]
    kpi_table = [
        {**m, "display": _fmt_metric(m["value"], m["fmt"])} for m in metric_rows
    ]
    inventory = []
    for t in pack.get("tables", []):
        did = t.get("dataset_id") or t.get("active_dataset_id")
        ds_name, n = "–", 0
        if did:
            ds_name = ds_names.get(did, "Dataset")
            n = len(t.get("rows", []))
        inventory.append(
            {
                "label": t.get("label") or t["key"],
                "entity": t.get("entity_key", "–"),
                "dataset": ds_name,
                "rows": n,
            }
        )

    sections_used = [
        s
        for s, on in [
            ("summary", True),
            ("qa", "qa" in sections and bool(qa_view)),
            ("evidence", section_chain),
            ("kpi", "kpi" in sections and bool(kpi_table)),
            ("charts", section_charts),
            ("ontology", section_ontology),
            ("analytics", section_analytics),
            ("ai", bool(ai_text)),
            ("appendix", True),
        ]
        if on
    ]
    tpl = Environment(loader=BaseLoader(), autoescape=False).from_string(_MD_TEMPLATE)
    md = tpl.render(
        title=title,
        date=datetime.utcnow().strftime("%Y-%m-%d"),
        pack_name=pack_name,
        pack_label=("None — text-only report" if text_only else pack_name),
        text_only=text_only,
        scope=scope.replace("_", " ").title(),
        qa_count=len(qa_items),
        takeaways=takeaways,
        kpi_cards=kpi_cards,
        section_qa=("qa" in sections and bool(qa_view)),
        qa_items=qa_view,
        section_chain=section_chain,
        n_chain=n_chain,
        glossary=glossary,
        formula_rows=formula_rows,
        section_kpi=("kpi" in sections and bool(kpi_table)),
        n_kpi=n_kpi,
        kpi_table=kpi_table,
        section_charts=section_charts,
        n_charts=n_charts,
        charts=charts_meta,
        section_ontology=section_ontology,
        n_ontology=n_ontology,
        section_analytics=section_analytics,
        n_analytics=n_analytics,
        att_rows=att_rows,
        att_label=(att_data or {}).get("label", ""),
        ag_rows=ag_rows,
        ag_label=(ag_data or {}).get("label", ""),
        ai_text=ai_text,
        n_ai=n_ai,
        n_appendix=n_appendix,
        inventory=inventory,
        uid=uid,
        generated=now(),
        sections_used=", ".join(sections_used),
        ai_status=ai_status,
    )

    md_path = os.path.join(rdir, "report.md")
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(md)

    html_path = _render_html(
        md, rdir, title, "None — text-only report" if text_only else pack_name
    )
    pdf_path = _render_pdf(
        md,
        rdir,
        title,
        kpi_cards,
        "None — text-only report" if text_only else pack_name,
    )

    cur = conn.execute(
        "INSERT INTO reports(uid,owner_id,pack_id,title,scope,sections,include_ai,status,"
        "qa_count,md_path,html_path,pdf_path,created_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?)",
        (
            uid,
            owner_id,
            pid,
            title,
            scope,
            _json.dumps(sections_used),
            1 if ai_text else 0,
            "ready",
            len(qa_items),
            os.path.relpath(md_path, DATA_ROOT),
            os.path.relpath(html_path, DATA_ROOT),
            os.path.relpath(pdf_path, DATA_ROOT),
            now(),
        ),
    )
    rid = int(cur.lastrowid)
    audit(
        conn,
        actor,
        "report.generate",
        f"uid={uid} qa={len(qa_items)} ai={bool(ai_text)}",
    )
    return {
        "id": rid,
        "uid": uid,
        "dir": rdir,
        "md_path": md_path,
        "html_path": html_path,
        "pdf_path": pdf_path,
        "sections": sections_used,
        "ai_included": bool(ai_text),
    }


def _render_html(md: str, rdir: str, title: str, pack_name: str) -> str:
    """Render the Markdown report to a self-contained HTML file.

    Every referenced PNG is base64-embedded so the HTML file stands alone.

    Args:
        md (str): Canonical Markdown report source.
        rdir (str): Report directory that chart images are resolved against.
        title (str): Report title used in the HTML ``<title>``.
        pack_name (str): Ontology pack name shown in the footer.

    Returns:
        str: Absolute path of the written ``report.html``.

    Raises:
        OSError: If the HTML file cannot be written.

    Example:
        >>> _render_html(md, rdir, "Q3 review", "Insurance pack")
    """
    fragment = md_to_html_fragment(md)
    # base64-embed every referenced PNG -> truly self-contained single file.
    asset_map = {}
    for m in re.finditer(r"!\[[^\]]*\]\(([^)]+)\)", md):
        rel = m.group(1)
        ap = os.path.normpath(os.path.join(rdir, rel))
        if ap.startswith(rdir) and os.path.exists(ap):
            with open(ap, "rb") as f:
                asset_map[rel] = base64.b64encode(f.read()).decode("ascii")
    fragment = _embed_images(fragment, asset_map)
    # Style Q&A blocks: wrap h3+paragraph pairs is unnecessary; add class via wrapper.
    tpl = Environment(loader=BaseLoader()).from_string(_HTML_SHELL)
    page = tpl.render(
        title=html.escape(title),
        body=fragment,
        generated=now(),
        pack_name=html.escape(pack_name),
    )
    path = os.path.join(rdir, "report.html")
    with open(path, "w", encoding="utf-8") as f:
        f.write(page)
    return path


