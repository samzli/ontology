def _render_html(md: str, rdir: str, title: str, pack_name: str) -> str:
    fragment = md_to_html_fragment(md)
    # base64-embed every referenced PNG -> truly self-contained single file.
    asset_map = {}
    for m in re.finditer(r"!\[[^\]]*\]\(([^)]+)\)", md):
        rel = m.group(1)
        ap = os.path.normpath(os.path.join(rdir, rel))
        if ap.startswith(rdir) and os.path.exists(ap):
            with open(ap, "rb") as f:
                asset_map[rel] = base64.b64encode(f.read()).decode("ascii")
    fragment = _embed_images(fragment, asset_map)
    # Style Q&A blocks: wrap h3+paragraph pairs is unnecessary; add class via wrapper.
    tpl = Environment(loader=BaseLoader()).from_string(_HTML_SHELL)
    page = tpl.render(
        title=html.escape(title),
        body=fragment,
        generated=now(),
        pack_name=html.escape(pack_name),
    )
    path = os.path.join(rdir, "report.html")
    with open(path, "w", encoding="utf-8") as f:
        f.write(page)
    return path


def _render_pdf(
    md: str, rdir: str, title: str, kpi_cards: List[Dict[str, str]], pack_name: str
) -> str:
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        BaseDocTemplate,
        Frame,
        Image,
        PageBreak,
        PageTemplate,
        Paragraph,
        Spacer,
        Table,
        TableStyle,
        NextPageTemplate,
    )

    navy = colors.HexColor(BRAND_NAVY)
    red = colors.HexColor(BRAND_RED)
    full_width = A4[0] - 36 * mm

    styles = {
        "H1": ParagraphStyle(
            "H1",
            fontName="Helvetica-Bold",
            fontSize=15,
            textColor=navy,
            spaceBefore=14,
            spaceAfter=6,
            borderPadding=(0, 0, 3, 0),
            leading=18,
        ),
        "H2": ParagraphStyle(
            "H2",
            fontName="Helvetica-Bold",
            fontSize=12.5,
            textColor=navy,
            spaceBefore=12,
            spaceAfter=5,
            leading=15,
        ),
        "H3": ParagraphStyle(
            "H3",
            fontName="Helvetica-Bold",
            fontSize=10.8,
            textColor=colors.HexColor("#33414F"),
            spaceBefore=8,
            spaceAfter=3,
            leading=13,
        ),
        "H4": ParagraphStyle(
            "H4",
            fontName="Helvetica-Bold",
            fontSize=9.8,
            textColor=colors.HexColor("#33414F"),
            leading=12,
        ),
        "TD": ParagraphStyle(
            "TD",
            fontName="Helvetica",
            fontSize=8.8,
            leading=12,
            textColor=colors.HexColor("#1F2933"),
        ),
        "TH": ParagraphStyle(
            "TH",
            fontName="Helvetica-Bold",
            fontSize=8.8,
            leading=11,
            textColor=colors.white,
        ),
        "Caption": ParagraphStyle(
            "Caption",
            fontName="Helvetica-Oblique",
            fontSize=8,
            textColor=colors.HexColor("#66788A"),
            alignment=TA_LEFT,
        ),
        "CoverTitle": ParagraphStyle(
            "CoverTitle",
            fontName="Helvetica-Bold",
            fontSize=26,
            leading=32,
            textColor=navy,
        ),
        "CoverMeta": ParagraphStyle(
            "CoverMeta",
            fontName="Helvetica",
            fontSize=10.5,
            leading=16,
            textColor=colors.HexColor("#52606D"),
        ),
        "KpiValue": ParagraphStyle(
            "KpiValue",
            fontName="Helvetica-Bold",
            fontSize=15,
            leading=18,
            textColor=navy,
        ),
        "KpiLabel": ParagraphStyle(
            "KpiLabel",
            fontName="Helvetica",
            fontSize=7.6,
            leading=10,
            textColor=colors.HexColor("#66788A"),
        ),
    }

    path = os.path.join(rdir, "report.pdf")

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setStrokeColor(colors.HexColor("#E4E7EB"))
        canvas.setLineWidth(0.5)
        canvas.line(18 * mm, 14 * mm, A4[0] - 18 * mm, 14 * mm)
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(colors.HexColor("#66788A"))
        canvas.drawString(18 * mm, 9 * mm, f"Onti · {pack_name}")
        canvas.drawRightString(A4[0] - 18 * mm, 9 * mm, f"Page {doc.page}")
        canvas.restoreState()

    doc = BaseDocTemplate(
        path,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title=title,
        author="Onti",
    )
    frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="body")
    cover_frame = Frame(
        doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="cover"
    )
    doc.addPageTemplates(
        [
            PageTemplate(id="Cover", frames=[cover_frame], onPage=lambda c, d: None),
            PageTemplate(id="Body", frames=[frame], onPage=footer),
        ]
    )

    story = []
    # ---- cover ---------------------------------------------------------
    story.append(Spacer(1, 30 * mm))
    story.append(
        Paragraph(
            "ONTI · ONTOLOGY ANALYSIS REPORT",
            ParagraphStyle(
                "eyebrow",
                fontName="Helvetica-Bold",
                fontSize=9,
                textColor=red,
                leading=14,
                spaceAfter=10,
            ),
        )
    )
    story.append(Paragraph(_inline_rl(title), styles["CoverTitle"]))
    story.append(Spacer(1, 8 * mm))
    story.append(
        Paragraph(
            f"Generated: {now()}<br/>Ontology pack: {_inline_rl(pack_name)}",
            styles["CoverMeta"],
        )
    )
    if kpi_cards:
        story.append(Spacer(1, 12 * mm))
        cells = []
        for c in kpi_cards:
            cells.append(
                [
                    Paragraph(_inline_rl(c["display"]), styles["KpiValue"]),
                    Paragraph(_inline_rl(c["label"]), styles["KpiLabel"]),
                ]
            )
        rows = []
        for i in range(0, len(cells), 3):
            row_cards = []
            for cv, cl in cells[i : i + 3]:
                inner = Table([[cv], [cl]], colWidths=[(full_width - 16) / 3])
                inner.setStyle(
                    TableStyle(
                        [
                            ("LINEBEFORE", (0, 0), (0, -1), 2.2, red),
                            ("BOX", (0, 0), (-1, -1), 0.6, colors.HexColor("#E4E7EB")),
                            (
                                "BACKGROUND",
                                (0, 0),
                                (-1, -1),
                                colors.HexColor("#FBFBFC"),
                            ),
                            ("TOPPADDING", (0, 0), (-1, -1), 8),
                            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                            ("LEFTPADDING", (0, 0), (-1, -1), 10),
                        ]
                    )
                )
                row_cards.append(inner)
            while len(row_cards) < 3:
                row_cards.append(Paragraph("", styles["TD"]))
            rows.append(row_cards)
        kt = Table(rows, colWidths=[full_width / 3] * 3)
        kt.setStyle(
            TableStyle(
                [
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("LEFTPADDING", (0, 0), (-1, -1), 4),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ]
            )
        )
        story.append(kt)
    story.append(NextPageTemplate("Body"))
    story.append(PageBreak())

    def image_loader(rel):
        ap = os.path.normpath(os.path.join(rdir, rel))
        if not ap.startswith(rdir) or not os.path.exists(ap):
            return None
        from PIL import Image as PILImage

        with PILImage.open(ap) as im:
            iw, ih = im.size
        max_w = full_width
        max_h = 105 * mm
        w = max_w
        h = w * ih / iw
        if h > max_h:
            h = max_h
            w = h * iw / ih
        return Image(ap, width=w, height=h)

    # Body content — strip the H1 title (already on the cover).
    body_md = re.sub(r"^#\s+.*$", "", md, count=1, flags=re.M)
    story += md_to_flowables(body_md, styles, image_loader, full_width)
    doc.build(story)
    return path


