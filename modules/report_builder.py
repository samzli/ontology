def _inline_rl(text: str) -> str:
    """Escape a string and convert inline Markdown for ReportLab paragraphs.

    Args:
        text (str): Markdown text to convert.

    Returns:
        str: ReportLab mini-HTML with code and bold markup applied.

    Example:
        >>> _inline_rl("**VNB** and `code`")
        '<b>VNB</b> and <font face="Courier" size="9">code</font>'
    """
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = re.sub(r"`([^`]+)`", r'<font face="Courier" size="9">\1</font>', text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", text)
    return text


def md_to_flowables(md: str, styles, image_loader, full_width):
    """Convert the Onti Markdown subset into ReportLab flowables.

    Supports headings, horizontal rules, tables, bullets, images and
    paragraphs; numeric list items fall through as plain paragraphs.

    Args:
        md (str): Markdown document to convert.
        styles (dict[str, ParagraphStyle]): Named styles for H1-H4, TH, TD and
            Caption elements.
        image_loader (Callable[[str], Any]): Maps a relative image path to a
            ReportLab Image flowable, or ``None`` when unavailable.
        full_width (float): Available body width in points, used for tables.

    Returns:
        list: ReportLab flowables ready to be appended to a document story.

    Raises:
        Exception: Propagated from ``image_loader`` when an image cannot be built.

    Example:
        >>> flows = md_to_flowables("## Head", styles, loader, 480)
    """
    from reportlab.lib import colors
    from reportlab.platypus import (
        Paragraph,
        Spacer,
        Table,
        TableStyle,
        ListFlowable,
        ListItem,
        HRFlowable,
        KeepTogether,
    )

    flows = []
    lines = (md or "").replace("\r\n", "\n").split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        if line.strip() == "---":
            flows.append(Spacer(1, 6))
            flows.append(
                HRFlowable(
                    width="100%", thickness=0.7, color=colors.HexColor("#E4E7EB")
                )
            )
            i += 1
            continue
        m = re.match(r"^(#{1,6})\s+(.*)$", line)
        if m:
            lvl = len(m.group(1))
            txt = _inline_rl(m.group(2))
            if lvl == 1:
                flows.append(Spacer(1, 10))
                flows.append(Paragraph(txt, styles["H1"]))
            elif lvl == 2:
                flows.append(Spacer(1, 12))
                p = Paragraph(txt, styles["H2"])
                flows.append(p)
            elif lvl == 3:
                flows.append(Spacer(1, 8))
                flows.append(Paragraph(txt, styles["H3"]))
            else:
                flows.append(Paragraph(txt, styles["H4"]))
            i += 1
            continue
        m = re.match(r"!\[([^\]]*)\]\(([^)]+)\)", line.strip())
        if m:
            img = image_loader(m.group(2))
            if img is not None:
                flows.append(Spacer(1, 6))
                flows.append(
                    KeepTogether(
                        [img, Spacer(1, 3), Paragraph(m.group(1), styles["Caption"])]
                    )
                )
            i += 1
            continue
        if line.lstrip().startswith("|"):
            tbl = []
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                tbl.append(lines[i].strip())
                i += 1
            rows = [[c.strip() for c in r.strip("|").split("|")] for r in tbl]
            rows = [
                r
                for r in rows
                if not all(re.fullmatch(r":?-{2,}:?", c or "") for c in r)
            ]
            if rows:
                ncol = max(len(r) for r in rows)
                grid = [r + [""] * (ncol - len(r)) for r in rows]
                data = [
                    [
                        Paragraph(
                            _inline_rl(c), styles["TH"] if ri == 0 else styles["TD"]
                        )
                        for c in r
                    ]
                    for ri, r in enumerate(grid)
                ]
                avail = full_width
                col_w = [avail / ncol] * ncol
                t = Table(data, colWidths=col_w, repeatRows=1, hAlign="LEFT")
                t.setStyle(
                    TableStyle(
                        [
                            (
                                "BACKGROUND",
                                (0, 0),
                                (-1, 0),
                                colors.HexColor(BRAND_NAVY),
                            ),
                            (
                                "ROWBACKGROUNDS",
                                (0, 1),
                                (-1, -1),
                                [colors.white, colors.HexColor("#F6F7F9")],
                            ),
                            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#D9DEE3")),
                            ("VALIGN", (0, 0), (-1, -1), "TOP"),
                            ("TOPPADDING", (0, 0), (-1, -1), 4),
                            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                            ("LEFTPADDING", (0, 0), (-1, -1), 5),
                        ]
                    )
                )
                flows.append(Spacer(1, 6))
                flows.append(t)
                flows.append(Spacer(1, 8))
            continue
        if re.match(r"^\s*[-*]\s+", line):
            items = []
            while i < len(lines) and re.match(r"^\s*[-*]\s+", lines[i]):
                items.append(
                    Paragraph(
                        _inline_rl(re.sub(r"^\s*[-*]\s+", "", lines[i])), styles["TD"]
                    )
                )
                i += 1
            flows.append(
                ListFlowable(
                    [ListItem(x, leftIndent=14, value="•") for x in items],
                    bulletType="bullet",
                    start="•",
                    leftIndent=14,
                )
            )
            flows.append(Spacer(1, 6))
            continue
        para = [line]
        i += 1
        while (
            i < len(lines)
            and lines[i].strip()
            and not re.match(r"^(#{1,6}\s|\s*[-*]\s|\s*\d+\.\s|\||---|!\[)", lines[i])
        ):
            para.append(lines[i])
            i += 1
        flows.append(
            Paragraph(_inline_rl(" ".join(p.strip() for p in para)), styles["TD"])
        )
        flows.append(Spacer(1, 5))
    return flows


