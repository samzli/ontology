  // so an administrator can judge whether to approve or reject it.
  function evidenceHtml(ev) {
    if (!ev || (!ev.table && !(ev.columns || []).length)) return '';
    const cols = ev.columns || [];
    const rows = ev.sample_rows || [];
    let html = '<div class="small mt8"><div class="muted">Proposing against</div>' +
      '<div class="mono">' + escHtml(ev.table_label || ev.table || '—') +
      '</div><div class="mt8 muted">Table columns</div>' +
      '<div class="flex wrap" style="gap:4px">' +
      cols.map((c) => '<span class="badge neutral">' + escHtml(c.key) + '</span>').join('') +
      '</div>';
    if (rows.length) {
      const keys = Object.keys(rows[0]);
      html += '<div class="mt8 muted">Sample rows the model saw</div>' +
        '<div class="table-wrap"><table class="data"><thead><tr>' +
        keys.map((k) => '<th>' + escHtml(k) + '</th>').join('') + '</tr></thead><tbody>' +
        rows.map((r) => '<tr>' + keys.map((k) => '<td class="small">' +
          escHtml(String(r[k] == null ? '—' : r[k]).slice(0, 40)) + '</td>').join('') +
          '</tr>').join('') + '</tbody></table></div>';
    }
    return html + '</div>';
  }

