  function fieldHtml(f, val) {
    const id = 'of_' + f.k;
    if (f.type === 'bool') {
      return '<label class="fld switch" style="font-weight:600;color:var(--ink-2);margin:4px 0 12px">' +
        '<input type="checkbox" id="' + id + '"' + (val ? ' checked' : '') + '>' +
        '<span class="track"></span>' + f.label + '</label>';
    }
    let inner;
    const v = val == null ? '' : (Array.isArray(val) ? val.join(', ') : val);
    if (f.type === 'select') {
      const opts = (typeof f.opts === 'function' ? f.opts() : f.opts);
      inner = '<select id="' + id + '"><option value=""></option>' + opts.map((o) =>
        '<option value="' + escHtml(o) + '"' + (o === val ? ' selected' : '') + '>' +
        escHtml(o) + '</option>').join('') + '</select>';
    } else if (f.type === 'textarea' || (f.type === 'list' && f.lines >= 3)) {
      const rows = f.lines || 4;
      const raw = Array.isArray(val) ?
        (f.k === 'patterns' || f.k === 'require_groups' || f.k === 'guards' ? val.join('\n') : val.join(', '))
        : (val || '');
      inner = '<textarea id="' + id + '" rows="' + rows + '">' + escHtml(raw) + '</textarea>';
    } else {
      inner = '<input type="' + (f.type === 'number' ? 'number' : 'text') + '" id="' + id +
        '" value="' + escHtml(v) + '">';
    }
    return '<label class="fld"><span>' + f.label + (f.req ? ' *' : '') +
      (f.hint ? ' <span class="hint">' + f.hint + '</span>' : '') + '</span>' + inner + '</label>';
  }

  function readForm(kind, box, editing) {
    const payload = {};
    for (const f of FIELDS[kind]) {
      const node = box.querySelector('#of_' + f.k);
      if (!node) continue;
      if (f.type === 'bool') payload[f.k] = node.checked;
      else if (f.type === 'number') payload[f.k] = node.value === '' ? null : Number(node.value);
      else if (f.type === 'list') {
        const raw = node.value.trim();
        if (!raw) { payload[f.k] = []; continue; }
        if (f.k === 'patterns' || f.k === 'require_groups' || f.k === 'guards')
          payload[f.k] = raw.split('\n').map((x) => x.trim()).filter(Boolean);
        else payload[f.k] = raw.split(',').map((x) => x.trim()).filter(Boolean);
      } else payload[f.k] = node.value.trim();
    }
    return payload;
  }

