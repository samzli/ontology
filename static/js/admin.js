  // One renderer for every connection test: success shows the latency, a
  // negative verdict shows the translated cause, the next step, and the
  // provider's raw reply. A failed test is a valid answer (HTTP 200 with
  // ok:false), not an exception.
  function modelTestHtml(r) {
    if (r && r.ok) {
      return '<span style="color:var(--green)">✓ Connected in ' +
        Math.round(r.latency_ms || 0) + ' ms</span>';
    }
    const hint = r && r.hint
      ? '<div class="small muted mt4">' + escHtml(r.hint) + '</div>' : '';
    const raw = r && r.provider_error
      ? '<div class="small muted mt4" style="word-break:break-word">Provider said: ' +
      escHtml(r.provider_error) + '</div>' : '';
    return '<span style="color:var(--red-dark)">✕ ' +
      escHtml((r && r.error) || 'Test failed') + '</span>' + hint + raw;
  }

  function modelForm(m) {
    const body = document.createElement('div');
    // Show which key is already stored so "leave blank" is unambiguous, and
    // stop password managers from autofilling this field: an autofilled value
    // silently replaces the key the administrator just pasted, which surfaces
    // as the provider's "Token is invalid".
    const storedMasked = (m && m.api_key_masked) ? m.api_key_masked : '';
    const keyHint = storedMasked
      ? '<span class="hint">stored: ' + escHtml(storedMasked) + ' — leave blank to keep it</span>'
      : (m ? '<span class="hint">no key stored yet</span>' : '');
    const keyPlaceholder = storedMasked ? ('Keep ' + storedMasked) : 'sk-...';
    body.innerHTML =
      '<div class="form-row"><label class="fld"><span>Display name *</span><input id="mmName"></label>' +
      '<label class="fld"><span>Model id * <span class="hint">e.g. deepseek-chat, gpt-4o-mini</span></span><input id="mmModel"></label></div>' +
      '<label class="fld"><span>Base URL * <span class="hint">OpenAI-compatible root, e.g. https://api.openai.com/v1</span></span>' +
      '<input id="mmUrl" type="url" placeholder="https://host/v1"></label>' +
      '<label class="fld"><span>API key ' + keyHint + '</span>' +
      '<input id="mmKey" type="password" autocomplete="new-password" spellcheck="false" ' +
      'name="onti-model-api-key" placeholder="' + escHtml(keyPlaceholder) + '"></label>' +
      '<div class="form-row"><label class="fld"><span>Temperature</span><input id="mmTemp" type="number" step="0.05" min="0" max="2"></label>' +
      '<label class="fld"><span>Max tokens</span><input id="mmMax" type="number" min="64" max="32000"></label>' +
      '<label class="fld"><span>Timeout (s)</span><input id="mmTimeout" type="number" min="5" max="600"></label></div>' +
      '<label class="switch"><input type="checkbox" id="mmEnabled"><span class="track"></span>Enabled for use</label>' +
      '<label class="switch"><input type="checkbox" id="mmVerifySSL"><span class="track"></span>Verify SSL certificate ' +
      '<span class="hint">Uncheck for self-signed gateways (e.g. Deloitte Nova)</span></label>' +
      '<div class="small mt8" id="mmTestOut"></div>';
    const v = (id, val) => body.querySelector(id).value = val;
    v('#mmTemp', 0.3); v('#mmMax', 1024); v('#mmTimeout', 90);
    body.querySelector('#mmEnabled').checked = true;
    body.querySelector('#mmVerifySSL').checked = true;
    if (m) {
      v('#mmName', m.name); v('#mmModel', m.model); v('#mmUrl', m.base_url);
      v('#mmTemp', m.temperature); v('#mmMax', m.max_tokens); v('#mmTimeout', m.timeout);
      body.querySelector('#mmEnabled').checked = !!m.enabled;
      body.querySelector('#mmVerifySSL').checked =
        m.verify_ssl !== false;
    }

    const test = el('button', { class: 'btn btn-ghost' }, 'Test settings');
    const ok = el('button', { class: 'btn btn-primary' }, m ? 'Save' : 'Add model');
    const cancel = el('button', { class: 'btn btn-ghost' }, 'Cancel');
    const modal = openModal({
      title: m ? 'Edit model' : 'Add model', body,
      footer: [test, el('span', { class: 'spacer' }), cancel, ok], wide: true
    });
    cancel.onclick = () => modal.close();
    const payload = () => ({
      name: body.querySelector('#mmName').value.trim(),
      model: body.querySelector('#mmModel').value.trim(),
      base_url: body.querySelector('#mmUrl').value.trim(),
      // Trim here too: a pasted key very often carries a trailing newline or
      // space, which the provider answers with "Token is invalid".
      api_key: body.querySelector('#mmKey').value.trim(),
      temperature: Number(body.querySelector('#mmTemp').value),
      max_tokens: Number(body.querySelector('#mmMax').value),
      timeout: Number(body.querySelector('#mmTimeout').value),
      verify_ssl: body.querySelector('#mmVerifySSL').checked,
      enabled: body.querySelector('#mmEnabled').checked,
    });
    test.onclick = async () => {
      const p = payload();
      const out = body.querySelector('#mmTestOut');
      out.innerHTML = '<span class="muted">Testing…</span>';
      try {
        const r = await api.post('/api/admin/models/test',
          m && !p.api_key ? { config_id: m.id, verify_ssl: p.verify_ssl } :
            { base_url: p.base_url, model: p.model, api_key: p.api_key, name: p.name, verify_ssl: p.verify_ssl });
        out.innerHTML = modelTestHtml(r);
      } catch (e) {
        // Show the translated cause first, then the next step, and only then
        // the provider's raw text — the raw JSON alone is unactionable.
        const extra = e.extra || {};
        const hint = extra.hint
          ? '<div class="small muted mt4">' + escHtml(extra.hint) + '</div>' : '';
        const raw = extra.provider_error
          ? '<div class="small muted mt4" style="word-break:break-word">Provider said: ' +
          escHtml(extra.provider_error) + '</div>' : '';
        out.innerHTML =
          '<span style="color:var(--red-dark)">✕ ' + escHtml(e.message) + '</span>' + hint + raw;
      }
    };
    ok.onclick = async () => {
      const p = payload();
      try {
        if (m) {
          if (!p.api_key) p.api_key = '__unchanged__';
          await api.put('/api/admin/models/' + m.id, p);
        } else await api.post('/api/admin/models', p);
        modal.close(); toast('Model saved.', 'ok'); loadModels();
      } catch (e) { toast(e.message, 'err'); }
    };
  }

