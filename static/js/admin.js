  async function loadUsers() {
    const { users } = await api.get('/api/admin/users');
    const host = document.getElementById('usersGrid');
    host.innerHTML = '<div class="card"><div class="card-b tight"><div class="table-wrap"><table class="data">' +
      '<thead><tr><th>User</th><th>Display name</th><th>Role</th><th>Status</th><th>Created</th><th style="width:230px"></th></tr></thead><tbody>' +
      users.map((u) => '<tr><td class="mono">' + escHtml(u.username) + '</td><td>' + escHtml(u.display_name) +
        '</td><td><span class="role-tag ' + u.role + '">' + u.role + '</span></td>' +
        '<td>' + (u.enabled ? '<span class="badge rules">active</span>' : '<span class="badge red">disabled</span>') +
        '</td><td class="small muted">' + fmtDate(u.created_at) + '</td>' +
        '<td><button class="btn btn-ghost btn-xs" data-a="role">' + (u.role === 'admin' ? 'Demote' : 'Promote') + '</button> ' +
        '<button class="btn btn-ghost btn-xs" data-a="enable">' + (u.enabled ? 'Disable' : 'Enable') + '</button> ' +
        '<button class="btn btn-ghost btn-xs" data-a="pw">Reset pw</button></td></tr>').join('') +
      '</tbody></table></div></div></div>';
    host.querySelectorAll('tbody tr').forEach((tr, i) => {
      const u = users[i];
      const bind = (act, fn) => tr.querySelector('[data-a=' + act + ']').onclick = fn;
      bind('role', () => confirmAction(u.role === 'admin' ?
        'Demote "' + u.username + '" to regular user?' :
        'Promote "' + u.username + '" to administrator?', async () => {
          await api.post('/api/admin/users/' + u.id + '/role',
            { value: u.role === 'admin' ? 'user' : 'admin' });
          toast('Role updated.', 'ok'); loadUsers();
        }, { danger: u.role === 'user', yesText: 'Change role' }));
      bind('enable', () => confirmAction(u.enabled ? 'Disable "' + u.username + '"?' :
        'Enable "' + u.username + '"?', async () => {
          await api.post('/api/admin/users/' + u.id + '/enabled', { value: !u.enabled });
          toast('Updated.', 'ok'); loadUsers();
        }, { danger: u.enabled, yesText: 'Update' }));
      bind('pw', () => {
        const body = document.createElement('div');
        body.innerHTML = '<label class="fld"><span>New password (min 8 chars)</span>' +
          '<input type="password" id="npw"></label>';
        const ok = el('button', { class: 'btn btn-primary' }, 'Reset password');
        const cancel = el('button', { class: 'btn btn-ghost' }, 'Cancel');
        const m = openModal({ title: 'Reset password · ' + u.username, body, footer: [cancel, ok] });
        cancel.onclick = () => m.close();
        ok.onclick = async () => {
          const pw = body.querySelector('#npw').value;
          if (pw.length < 8) return toast('Minimum 8 characters.', 'warn');
          await api.post('/api/admin/users/' + u.id + '/reset-password', { value: pw });
          m.close(); toast('Password reset.', 'ok');
        };
      });
    });
  }

